#!/usr/bin/env python3
"""
Generate a 16x16 CJK bitmap font for retro-go from a TrueType/TrueType Collection font.

Usage:
    python3 gen_cjk_font.py <font.ttc> <output.c> [face_index]

Output format (type=2):
    Each glyph entry: [cp_hi, cp_lo, row0_hi, row0_lo, ..., row15_hi, row15_lo]
    = 2 + 32 = 34 bytes per glyph, sorted by Unicode codepoint.
    Row bits: bit 15 (MSB) = leftmost pixel, bit 0 = rightmost pixel.
"""

import sys
import freetype

FONT_SIZE = 16  # 16x16 pixels


def get_gb2312_codepoints():
    """Return sorted list of Unicode codepoints in GB2312."""
    codepoints = set()
    for zone in range(16, 88):
        for pos in range(1, 95):
            try:
                gb_bytes = bytes([0xA0 + zone, 0xA0 + pos])
                char = gb_bytes.decode('gb2312')
                cp = ord(char)
                if cp > 0x7F:
                    codepoints.add(cp)
            except (UnicodeDecodeError, ValueError):
                pass
    return sorted(codepoints)


def get_extra_codepoints():
    """Additional characters commonly needed for CJK text."""
    ranges = [
        (0x3000, 0x303F),  # CJK Symbols and Punctuation
        (0x3040, 0x309F),  # Hiragana
        (0x30A0, 0x30FF),  # Katakana
        (0xFF00, 0xFFEF),  # Halfwidth and Fullwidth Forms
    ]
    codepoints = []
    for start, end in ranges:
        codepoints.extend(range(start, end + 1))
    return codepoints


def render_char(face, codepoint, size=FONT_SIZE):
    """Render a character to a size x size bitmap.

    Returns a list of `size` uint16 values.
    Each uint16: bit 15 = leftmost pixel (x=0), bit 0 = rightmost pixel (x=15).
    """
    try:
        face.load_char(chr(codepoint), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_MONOCHROME | freetype.FT_LOAD_NO_HINTING)
    except freetype.FT_Exception:
        return None

    g = face.glyph
    bmp = g.bitmap

    if bmp.width == 0 or bmp.rows == 0:
        return None

    ascender = face.size.ascender >> 6
    top = ascender - g.bitmap_top  # first row in the size×size cell
    # Clamp so the glyph stays within the cell
    if top + bmp.rows > size:
        top = size - bmp.rows
    if top < 0:
        top = 0

    rows = [0] * size
    buf = bytes(bmp.buffer)

    for row in range(bmp.rows):
        dst_row = top + row
        if dst_row < 0 or dst_row >= size:
            continue
        for col in range(bmp.width):
            byte_idx = row * bmp.pitch + (col >> 3)
            bit_idx = 7 - (col & 7)
            if byte_idx < len(buf) and (buf[byte_idx] >> bit_idx) & 1:
                dst_col = g.bitmap_left + col
                if 0 <= dst_col < size:
                    rows[dst_row] |= (1 << (size - 1 - dst_col))

    # Return None if all rows are empty (no visible pixels)
    if all(r == 0 for r in rows):
        return None

    return rows


def generate_font(ttc_path, output_path, face_index=1):
    print(f"Loading font: {ttc_path} (face index {face_index})")
    face = freetype.Face(ttc_path, index=face_index)
    face.set_pixel_sizes(FONT_SIZE, FONT_SIZE)
    print(f"  Family: {face.family_name.decode()}, Style: {face.style_name.decode()}")
    print(f"  Num glyphs: {face.num_glyphs}")

    # Collect all target codepoints
    all_cps = sorted(set(get_gb2312_codepoints() + get_extra_codepoints()))
    print(f"Target codepoints: {len(all_cps)}")

    # Render glyphs
    glyphs = []
    skipped = 0
    for cp in all_cps:
        glyph_index = face.get_char_index(cp)
        if glyph_index == 0:
            skipped += 1
            continue
        rows = render_char(face, cp)
        if rows is None:
            skipped += 1
            continue
        glyphs.append((cp, rows))

    print(f"Valid glyphs: {len(glyphs)}, skipped: {skipped}")

    # Write C source file
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('#include "../rg_gui.h"\n\n')
        f.write(f'// WenQuanYi Zen Hei Mono {FONT_SIZE}x{FONT_SIZE} CJK bitmap font\n')
        f.write(f'// {len(glyphs)} glyphs, sorted by Unicode codepoint\n')
        f.write('//\n')
        f.write('// Data format per glyph (34 bytes):\n')
        f.write('//   [cp_hi, cp_lo, row0_hi, row0_lo, ..., row15_hi, row15_lo]\n')
        f.write('// Row bit order: bit15=leftmost pixel, bit0=rightmost pixel\n')
        f.write('// Generated by tools/gen_cjk_font.py\n\n')

        # Inline data directly into the struct (rg_font_t uses a flexible array member;
        # GCC supports brace-initializing it, but not assigning from a pointer).
        f.write(f'const rg_font_t font_ZenHei{FONT_SIZE} = {{\n')
        f.write(f'    .name = "ZenHei{FONT_SIZE}",\n')
        f.write(f'    .type = 2,\n')
        f.write(f'    .width = {FONT_SIZE},\n')
        f.write(f'    .height = {FONT_SIZE},\n')
        f.write(f'    .chars = {len(glyphs)},\n')
        f.write(f'    .data = {{\n')

        for cp, rows in glyphs:
            try:
                char_repr = chr(cp)
            except Exception:
                char_repr = '?'
            f.write(f'        // U+{cp:04X} {char_repr}\n')
            f.write(f'        0x{(cp >> 8) & 0xFF:02X}, 0x{cp & 0xFF:02X},')

            row_bytes = []
            for row in rows:
                row_bytes.append(f'0x{(row >> 8) & 0xFF:02X},0x{row & 0xFF:02X}')

            # Write 8 rows per line for readability
            for i in range(0, FONT_SIZE, 8):
                chunk = row_bytes[i:i+8]
                f.write('\n        ' + ','.join(chunk) + ',')
            f.write('\n')

        f.write('    },\n')
        f.write('};\n')

    print(f"Written to: {output_path}")
    import os
    size_kb = os.path.getsize(output_path) / 1024
    print(f"File size: {size_kb:.1f} KB")
    print(f"Flash usage estimate: {len(glyphs) * 34 / 1024:.1f} KB")


if __name__ == '__main__':
    if len(sys.argv) < 3:
        print(f"Usage: {sys.argv[0]} <font.ttc> <output.c> [face_index=1]")
        sys.exit(1)
    ttc_path = sys.argv[1]
    output_path = sys.argv[2]
    face_index = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    generate_font(ttc_path, output_path, face_index)
