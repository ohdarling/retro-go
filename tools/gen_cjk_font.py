#!/usr/bin/env python3
"""
Generate a CJK bitmap font for retro-go using the new rg_font_glyph_t format.

Usage:
    python3 gen_cjk_font.py <font.ttc> <output.c> [face_index] [font_size]

Output uses the same packed glyph format as font_converter.py:
  rg_font_glyph_t: {uint16_t code, uint8_t yOffset, width, height, xOffset, xDelta, data[]}
  Terminated by a glyph with code=0x0000.
"""

import sys
import freetype

FONT_SIZE = 16


def get_gb2312_codepoints():
    """Return sorted list of Unicode codepoints in GB2312."""
    codepoints = set()
    for zone in range(16, 88):
        for pos in range(1, 95):
            try:
                gb_bytes = bytes([0xA0 + zone, 0xA0 + pos])
                char = gb_bytes.decode('gb2312')
                cp = ord(char)
                if cp > 0x7F:
                    codepoints.add(cp)
            except (UnicodeDecodeError, ValueError):
                pass
    return sorted(codepoints)


def get_extra_codepoints():
    """Additional characters commonly needed for CJK text."""
    ranges = [
        (0x3000, 0x303F),  # CJK Symbols and Punctuation
        (0x3040, 0x309F),  # Hiragana
        (0x30A0, 0x30FF),  # Katakana
        (0xFF00, 0xFFEF),  # Halfwidth and Fullwidth Forms
    ]
    codepoints = []
    for start, end in ranges:
        codepoints.extend(range(start, end + 1))
    return codepoints


def render_char(face, codepoint, size=FONT_SIZE):
    """Render a character and return (yOffset, width, height, xOffset, xDelta, packed_data)
    or None if no glyph."""
    try:
        face.load_char(chr(codepoint),
                       freetype.FT_LOAD_RENDER | freetype.FT_LOAD_MONOCHROME | freetype.FT_LOAD_NO_HINTING)
    except freetype.FT_Exception:
        return None

    g = face.glyph
    bmp = g.bitmap

    if bmp.width == 0 or bmp.rows == 0:
        return None

    width = bmp.width
    height = bmp.rows
    ascender = face.size.ascender >> 6
    yOffset = ascender - g.bitmap_top
    # Clamp to fit in cell
    if yOffset + height > size:
        yOffset = size - height
    if yOffset < 0:
        yOffset = 0
    xOffset = g.bitmap_left
    if xOffset < 0:
        xOffset = 0
    xDelta = g.advance.x >> 6

    # Pack bitmap data: MSB first, 8 pixels per byte (same as proportional font format)
    buf = bytes(bmp.buffer)
    bits = []
    for row in range(height):
        for col in range(width):
            byte_idx = row * bmp.pitch + (col >> 3)
            bit_idx = 7 - (col & 7)
            if byte_idx < len(buf) and (buf[byte_idx] >> bit_idx) & 1:
                bits.append(1)
            else:
                bits.append(0)

    # Pack bits into bytes
    packed = []
    for i in range(0, len(bits), 8):
        byte = 0
        for j in range(8):
            if i + j < len(bits) and bits[i + j]:
                byte |= (0x80 >> j)
        packed.append(byte)

    return (yOffset, width, height, xOffset, xDelta, packed)


def generate_font(ttc_path, output_path, face_index=1, size=FONT_SIZE):
    print(f"Loading font: {ttc_path} (face index {face_index}, size {size})")
    face = freetype.Face(ttc_path, index=face_index)
    face.set_pixel_sizes(size, size)
    print(f"  Family: {face.family_name.decode()}, Style: {face.style_name.decode()}")

    all_cps = sorted(set(get_gb2312_codepoints() + get_extra_codepoints()))
    print(f"Target codepoints: {len(all_cps)}")

    glyphs = []
    skipped = 0
    for cp in all_cps:
        if face.get_char_index(cp) == 0:
            skipped += 1
            continue
        result = render_char(face, cp, size)
        if result is None:
            skipped += 1
            continue
        glyphs.append((cp, result))

    print(f"Valid glyphs: {len(glyphs)}, skipped: {skipped}")

    total_data = sum(len(g[1][5]) for g in glyphs)
    total_bytes = len(glyphs) * 7 + total_data + 7  # +7 for terminator
    print(f"Flash usage: {total_bytes / 1024:.1f} KB")

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('#include "../rg_gui.h"\n\n')
        f.write(f'// WenQuanYi Zen Hei Mono {size}px CJK font ({len(glyphs)} glyphs)\n')
        f.write('// Uses rg_font_glyph_t format, generated by tools/gen_cjk_font.py\n\n')

        f.write(f'const rg_font_t font_ZenHei{size} = {{\n')
        f.write(f'    .name = "ZenHei {size}",\n')
        f.write(f'    .type = 1,\n')  # proportional, same traversal as other fonts
        f.write(f'    .width = {size},\n')
        f.write(f'    .height = {size},\n')
        f.write(f'    .chars = {len(glyphs)},\n')
        f.write(f'    .data = {{\n')

        for cp, (yOff, w, h, xOff, xDelta, packed) in glyphs:
            char_repr = chr(cp)
            code_lo = cp & 0xFF
            code_hi = (cp >> 8) & 0xFF
            f.write(f'        /* U+{cp:04X} {char_repr} */\n')
            f.write(f'        0x{code_lo:02X}, 0x{code_hi:02X}, '
                    f'0x{yOff:02X}, 0x{w:02X}, 0x{h:02X}, 0x{xOff:02X}, 0x{xDelta:02X},\n')
            if packed:
                for i in range(0, len(packed), 16):
                    chunk = packed[i:i+16]
                    f.write('        ' + ', '.join(f'0x{b:02X}' for b in chunk) + ',\n')

        # Terminator: code=0x0000
        f.write('        /* End */\n')
        f.write('        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,\n')
        f.write('    },\n')
        f.write('};\n')

    print(f"Written to: {output_path}")
    import os
    print(f"File size: {os.path.getsize(output_path) / 1024:.1f} KB")


if __name__ == '__main__':
    if len(sys.argv) < 3:
        print(f"Usage: {sys.argv[0]} <font.ttc> <output.c> [face_index=1] [font_size=16]")
        sys.exit(1)
    ttc_path = sys.argv[1]
    output_path = sys.argv[2]
    face_index = int(sys.argv[3]) if len(sys.argv) > 3 else 1
    font_size = int(sys.argv[4]) if len(sys.argv) > 4 else FONT_SIZE
    generate_font(ttc_path, output_path, face_index, font_size)
